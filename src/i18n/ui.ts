/** The same page in the other language. */
export function otherLangPath(pathname: string, lang: Lang): string {
  const other: Lang = lang === 'es' ? 'en' : 'es';
  const rest = pathname.replace(/^\/(es|en)(?=\/|$)/, '');
  return `/${other}${rest || '/'}`;
}
